async function seed() {
  await connectDB();

  // 清理旧数据
  await Category.deleteMany({});
  await Note.deleteMany({});

  const lines = rawData.split('\n');
  const categoriesToInsert = [];
  const notesToInsert = [];

  let currentL1 = null;
  let currentL2 = null;
  let currentL3 = null;
  let l1Order = 0;
  let l2Order = 0;
  let l3Order = 0;

  for (const rawLine of lines) {
    const line = rawLine.trim();
    if (!line) continue;

    if (line.startsWith('# ')) {
      l1Order += 1;
      currentL1 = new mongoose.Types.ObjectId();
      categoriesToInsert.push({
        _id: currentL1,
        name: line.replace('# ', '').trim(),
        level: 1,
        parentId: null,
        order: l1Order,
        createdAt: new Date()
      });
      currentL2 = null;
      currentL3 = null;
      l2Order = 0;
    } else if (line.startsWith('## ')) {
      l2Order += 1;
      currentL2 = new mongoose.Types.ObjectId();
      categoriesToInsert.push({
        _id: currentL2,
        name: line.replace('## ', '').trim(),
        level: 2,
        parentId: currentL1,
        order: l2Order,
        createdAt: new Date()
      });
      currentL3 = null;
      l3Order = 0;
    } else if (line.startsWith('### ')) {
      l3Order += 1;
      currentL3 = new mongoose.Types.ObjectId();
      categoriesToInsert.push({
        _id: currentL3,
        name: line.replace('### ', '').trim(),
        level: 3,
        parentId: currentL2 || currentL1,
        order: l3Order,
        createdAt: new Date()
      });
    } else {
      const parentCat = currentL3 || currentL2 || currentL1;
      if (!parentCat) continue;

      const isImportant = line.includes('高频') || line.includes('核心');
      const tags = [];
      if (line.includes('高频')) tags.push('高频');
      if (line.includes('公式') || line.includes('=')) tags.push('公式');

      // 标题去除 Markdown 星号，保持干净
      const cleanText = line.replace(/\*\*/g, '');
      const title = cleanText.length > 20 ? `${cleanText.substring(0, 20)}...` : cleanText;

      notesToInsert.push({
        categoryId: parentCat,
        title,
        content: line, // 保留带 ** 的 markdown 原文
        tags,
        isImportant,
        createdAt: new Date(),
        updatedAt: new Date()
      });
    }
  }

  if (categoriesToInsert.length > 0) await Category.insertMany(categoriesToInsert);
  if (notesToInsert.length > 0) await Note.insertMany(notesToInsert);

  // 确保默认管理员存在（admin / 123456）
  const admin = await User.findOne({ username: 'admin' });
  if (!admin) {
    await User.create({
      username: 'admin',
      password: hashPassword('123456'),
      nickname: '管理员',
      role: 'admin'
    });
    console.log('已创建默认管理员: admin / 123456');
  } else {
    console.log('管理员账号已存在，跳过创建');
  }

  console.log('=== 数据导入成功，Markdown 格式已完整保留！ ===');
  console.log(`分类总数: ${categoriesToInsert.length}`);
  console.log(`知识点笔记总数: ${notesToInsert.length}`);

  await mongoose.disconnect();
  process.exit(0);
}

