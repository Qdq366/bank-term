风险监测：通过对一些关键的风险指标和环节进行检测，关注银行风险的变化程度，建立风险预警机制。
风险控制：
风险分散：多样化投资、系数不为1、非系统性风险（鸡蛋不放在同一个篮子里）。
风险对冲：负相关，购买与标的资产收益波动负相关的某种资产。（万一这个赔了另一个不就赚了）
风险转移：保险，购买某种金融产品或采取其他合法的经济措施将风险转移给其他的经营主体。可分为保险转移和非保险转移。
风险规避：商业银行拒绝或退出某一业务或市信用风险监测的主要指标场，不做业务不承担风险。摆烂
